"""Write a trained model as a JS module the pack can import.

    python -I tools/toxicity/export.py <models dir>/<name> <out.js>

The weights are rounded to int8 with one scale per output (scale = largest
weight / 127) and stored as one base64 string, which is about 1.33 bytes of
text per weight; a number-array literal would be about 3.5. Levels come from
the trainer's report: for each output, the score at which the validation set
reached 95%, 85% and 70% precision. Unreachable levels are left out (null).
"""
import base64
import json
import math
import site
import sys
from pathlib import Path

sys.path.append(site.getusersitepackages())
import numpy as np

LABELS = ["toxic", "discrimination", "sexual", "hostility", "profanity"]

src = Path(sys.argv[1])
dest = Path(sys.argv[2])
z = np.load(src / "model.npz")
W, b, bits = z["W"].astype(np.float64), z["b"].astype(np.float64), int(z["bits"])
report = json.loads((src / "report.json").read_text())
# The features the trainer was given (featurize.mjs records them, train.py
# carries them over). Models from before 2026-11-26 evening don't say: 1.
FEATURE_VERSION = int(report.get("featureVersion", 1))

scales = np.abs(W).max(axis=0) / 127
q = np.clip(np.round(W / scales), -127, 127).astype(np.int8)
data = base64.b64encode(q.tobytes(order="C")).decode("ascii")


def threshold(lab, target):
    # Levels set on the archive (the server's own chat) win over the public
    # validation set when the trainer had them.
    if "export_levels" in report:
        t = report["export_levels"][lab][str(target)]
    else:
        t = report["categories"][lab]["levels"][str(target)]["threshold"]
    return None if t is None or not math.isfinite(t) else round(float(t), 4)


levels = {lab: {"low": threshold(lab, 0.95), "medium": threshold(lab, 0.85), "high": threshold(lab, 0.7)}
          for lab in LABELS}
spec = {
    "featureVersion": FEATURE_VERSION,
    "bits": bits,
    "outputs": LABELS,
    "scales": [float(f"{s:.8g}") for s in scales],
    "bias": [round(float(v), 6) for v in b],
    "levels": levels,
    "trainedOn": "Civil Comments (CC0), Measuring Hate Speech (CC BY 4.0), HateXplain (MIT), Admin+ templates",
    "name": src.name,
}
body = json.dumps({k: v for k, v in spec.items()}, indent=4)
body = body[:-2] + f',\n    "data": "{data}"\n}}'
dest.write_text(
    "// Generated by tools/toxicity/export.py from model " + src.name + ". Do not edit by hand.\n"
    "// Weights: int8, one scale per output, base64. See core/toxicity.js.\n"
    "export const TOX_MODEL = " + body + "\n",
    encoding="utf-8", newline="\n")
print(f"wrote {dest} ({dest.stat().st_size / 1024:.0f} KiB), {W.shape[0]:,} rows x {W.shape[1]} outputs")
